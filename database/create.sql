-- Trigger 9

CREATE OR REPLACE FUNCTION check_jobpost_location_requirement()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.work_model <> 'Remote' AND NEW.location_id IS NULL THEN
        RAISE EXCEPTION 
            'Non-remote job posts must have a valid location.';
    END IF;

    IF NEW.work_model = 'Remote' AND NEW.location_id IS NOT NULL THEN
        RAISE NOTICE 
            'Remote job post does not require a location!';
        NEW.location_id := NULL;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER enforce_jobpost_location_requirement
BEFORE INSERT OR UPDATE ON jobpost
FOR EACH ROW
EXECUTE FUNCTION check_jobpost_location_requirement();


