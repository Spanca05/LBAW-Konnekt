-- Trigger 11

CREATE OR REPLACE FUNCTION notify_matching_job_seekers()
RETURNS TRIGGER AS $$
DECLARE
    seeker RECORD;
    v_title TEXT;
    v_notification_id INTEGER;
BEGIN

    FOR seeker IN
        SELECT DISTINCT u.id
        FROM users u
        JOIN cv ON cv.jobseeker_id = u.id
        JOIN skill_cv scv ON scv.cv_id = cv.id
        JOIN skill_jobpost sjp ON sjp.skill_id = scv.skill_id
        WHERE u.role = 'JobSeeker'
          AND sjp.jobpost_id = NEW.id
          AND (
              (NEW.work_model = 'Remote' AND u.location_id IS NULL)   
              OR u.location_id = NEW.location_id  -- senão, só notifica se estiver na mesma localização
          )
    LOOP
        v_title := 'New job opportunity matching your skills: "' || NEW.title || '"';

        INSERT INTO notification (title, seen, date, type, jobpost_id, application_id)
        VALUES (
            v_title,
            FALSE,
            now(),
            'JobPostNotification',
            NEW.id,
            NULL
        )
        RETURNING id INTO v_notification_id;

        INSERT INTO user_notification (notification_id, user_id)
        VALUES (v_notification_id, seeker.id);
    END LOOP;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_notify_matching_job_seekers
AFTER INSERT ON jobpost
FOR EACH ROW
EXECUTE FUNCTION notify_matching_job_seekers();
