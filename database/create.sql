-- Create trigger function
CREATE FUNCTION jobpost_search_update() RETURNS TRIGGER AS $$
BEGIN
  -- On INSERT, always compute the tsvector
  IF TG_OP = 'INSERT' THEN
    NEW.tsvectors := (
      setweight(to_tsvector('english', NEW.title), 'A') ||
      setweight(to_tsvector('english', NEW.description), 'B')
    );
  END IF;

  -- On UPDATE, only recompute if relevant fields change
  IF TG_OP = 'UPDATE' THEN
    IF (NEW.title IS DISTINCT FROM OLD.title
        OR NEW.description IS DISTINCT FROM OLD.description) THEN
      NEW.tsvectors := (
        setweight(to_tsvector('english', NEW.title), 'A') ||
        setweight(to_tsvector('english', NEW.description), 'B')
      );
    END IF;
  END IF;

  RETURN NEW;
END $$
LANGUAGE plpgsql;

-- Trigger for automatic updates
CREATE TRIGGER jobpost_search_update
BEFORE INSERT OR UPDATE ON jobpost
FOR EACH ROW
EXECUTE PROCEDURE jobpost_search_update();

-- Create GIN index
CREATE INDEX idx_jobpost_search ON jobpost USING GIN (tsvectors);



