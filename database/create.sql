-- Note that a plural 'users' name was adopted because user is a reserved word in PostgreSQL.
CREATE TABLE location (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country TEXT NOT NULL,
    province TEXT NOT NULL,
    city TEXT NOT NULL,
    address TEXT NOT NULL,
    postal_code TEXT NOT NULL
);

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    role user_role NOT NULL, 
    password TEXT NOT NULL,
    phone_number TEXT NOT NULL,
    location_id INTEGER REFERENCES location(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL
);

CREATE TABLE category (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name category_name NOT NULL UNIQUE
);

CREATE TABLE jobpost (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employer_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category_id INTEGER NOT NULL REFERENCES category(id),
    location_id INTEGER REFERENCES location(id),
    title TEXT NOT NULL,
    salary NUMERIC NOT NULL,
    work_model work_model NOT NULL,
    description TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL
);

CREATE TABLE favourite_job (
    jobseeker_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    jobpost_id INTEGER NOT NULL REFERENCES jobpost(id) ON DELETE CASCADE,
    PRIMARY KEY (jobseeker_id, jobpost_id)
);

CREATE TABLE application (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jobseeker_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    jobpost_id INTEGER NOT NULL REFERENCES jobpost(id) ON DELETE CASCADE,
    motivation TEXT NOT NULL,
    date TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    status application_status DEFAULT 'Pending' NOT NULL,
    CONSTRAINT uq_application_jobseeker_jobpost UNIQUE (jobseeker_id, jobpost_id)
);

CREATE TABLE search_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    search TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL
);

CREATE TABLE cv (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jobseeker_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    description TEXT NOT NULL
);

CREATE TABLE skill (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL,
    name skill_name NOT NULL UNIQUE
);

CREATE TABLE skill_cv (
    cv_id INTEGER NOT NULL REFERENCES cv(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
    PRIMARY KEY (cv_id, skill_id)
);

CREATE TABLE skill_jobpost (
    jobpost_id INTEGER NOT NULL REFERENCES jobpost(id) ON DELETE CASCADE,
    skill_id INTEGER NOT NULL REFERENCES skill(id) ON DELETE CASCADE,
    PRIMARY KEY (jobpost_id, skill_id)
);

CREATE TABLE notification (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    seen BOOLEAN DEFAULT FALSE NOT NULL,
    date TIMESTAMP WITH TIME ZONE DEFAULT now() NOT NULL,
    type type_notification NOT NULL,
    jobpost_id INTEGER REFERENCES jobpost(id),
    application_id INTEGER REFERENCES application(id)
);

CREATE TABLE report (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reason TEXT NOT NULL,
    date DATE DEFAULT CURRENT_DATE NOT NULL,
    type type_report NOT NULL,
    reporter_id INTEGER REFERENCES users(id) NOT NULL,
    reported_jobpost_id INTEGER REFERENCES jobpost(id),
    reported_user_id INTEGER REFERENCES users(id)
);

CREATE TABLE user_notification (
    notification_id INTEGER NOT NULL REFERENCES notification(id) ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY (notification_id, user_id)
);

CREATE TABLE jobpost_category (
    category_id INTEGER NOT NULL REFERENCES category(id),
    jobpost_id INTEGER NOT NULL REFERENCES jobpost(id),
    PRIMARY KEY (category_id, jobpost_id)
);

CREATE TABLE skill_category (
    skill_id INTEGER NOT NULL REFERENCES skill(id),
    category_id INTEGER NOT NULL REFERENCES category(id)
);

