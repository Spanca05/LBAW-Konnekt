CREATE OR REPLACE FUNCTION user_soft_deletion()
RETURNS TRIGGER AS $$
DECLARE
    v_new_email TEXT;
    v_new_name TEXT;
    v_new_password TEXT;

BEGIN
    v_new_email := 'deleted_' || OLD.id || '@delete.app';
    v_new_name := 'Anonym' || OLD.id;
    v_new_password := 'DELETED_USER_' || OLD.id; 

    UPDATE users
    SET 
        name = v_new_name,                  
        email = v_new_email,                 
        password = v_new_password,           
        phone_number = '000000000',
        location_id = NULL,         
        updated_at = NOW()                   
    WHERE 
        id = OLD.id;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER soft_delete_user
BEFORE DELETE ON users
FOR EACH ROW
EXECUTE FUNCTION user_soft_deletion();


-- Trigger 4
CREATE OR REPLACE FUNCTION check_duplicate_application()
RETURNS TRIGGER AS $$
DECLARE
    count INTEGER;

BEGIN
    SELECT COUNT(*)
    INTO count
    FROM application
    WHERE jobseeker_id = NEW.jobseeker_id AND jobpost_id = NEW.jobpost_id;

    IF count > 0 THEN
        RAISE EXCEPTION 'A job seeker (ID: %) has already applied to this job post (ID: %). Duplicate application denied.', 
                        NEW.jobseeker_id, NEW.jobpost_id;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER prevent_duplicate_application
BEFORE INSERT ON application
FOR EACH ROW
EXECUTE FUNCTION check_duplicate_application();


